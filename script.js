function aiRenderChoices(choices){
  const el = document.getElementById("aiChoices");
  if(!el) return;
  el.innerHTML = choices.map((c, i) => `<button class="ai-choice-btn" data-choice="${i}">${c.label}</button>`).join("");
  el.dataset.map = JSON.stringify(choices.map(c => c.label));
  el._choices = choices;
}

