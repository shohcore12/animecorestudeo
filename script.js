function clearStallWatchdog(){ if(stallWatchdog){ clearTimeout(stallWatchdog); stallWatchdog = null; } }

function armStallWatchdog(video, errorBox){
  clearStallWatchdog();
  let lastTime = -1;
  stallWatchdog = setTimeout(function check(){
    if(video.paused || video.ended) return;
    if(video.currentTime === lastTime){ errorBox.classList.add("show"); return; }
    lastTime = video.currentTime;
    stallWatchdog = setTimeout(check, 5000);
  }, 5000);
}

function loadEpisode(seasonIndex, episodeIndex){
  playerState.seasonIndex = seasonIndex;
  playerState.episodeIndex = episodeIndex;

  const anime = playerState.anime;
  const season = anime.seasons[seasonIndex];
  const ep = season.episodes[episodeIndex];

  const video = document.getElementById("mainVideo");
  const emptyState = document.getElementById("playerEmpty");
  const errorBox = document.getElementById("playerError");
  const titleEl = document.getElementById("nowPlayingTitle");
  const retryBtn = document.getElementById("retryBtn");

  const hasSrc = Boolean(ep.src && ep.src.trim());

  clearStallWatchdog();
  stopWatchCommentary();
  errorBox.classList.remove("show");
  video.pause();
  video.removeAttribute("src");
  video.load();

  if(hasSrc){
    video.style.display = "block";
    emptyState.style.display = "none";
    video.src = ep.src;
    video.load();
    video.play().catch(() => {});
    armStallWatchdog(video, errorBox);

    video.onerror = () => { clearStallWatchdog(); errorBox.classList.add("show"); };
    video.onplaying = () => { errorBox.classList.remove("show"); clearStallWatchdog(); armStallWatchdog(video, errorBox); startWatchCommentary(); };
    video.onpause = () => { stopWatchCommentary(); };
    video.onended = () => { markWatched(anime.id, seasonIndex, episodeIndex); stopWatchCommentary(); };
    video.ontimeupdate = () => { if(video.currentTime > 3) markWatched(anime.id, seasonIndex, episodeIndex); };

    retryBtn.onclick = () => loadEpisode(seasonIndex, episodeIndex);
  } else {
    video.style.display = "none";
    emptyState.style.display = "flex";
  }

  const seasonLabel = anime.seasons.length > 1 ? `${season.name} \u00b7 ` : "";
  titleEl.innerHTML = `${seasonLabel}${ep.title}`;

  saveLastWatched(anime.id, seasonIndex, episodeIndex, anime.hue);
  renderSeasonTabs();
  renderEpisodeGrid();
  document.getElementById("playerFrame").scrollIntoView({ behavior: "smooth", block: "center" });
}

function saveLastWatched(animeId, seasonIndex, episodeIndex, hue){
  safeLocalSet("animecore-last-watched", { animeId, seasonIndex, episodeIndex, hue, ts: Date.now() });
}

function markWatched(animeId, seasonIndex, episodeIndex){
  const all = safeLocalGet("animecore-watched") || {};
  const key = `${animeId}:${seasonIndex}`;
  if(!all[key]) all[key] = [];
  if(!all[key].includes(episodeIndex)) all[key].push(episodeIndex);
  safeLocalSet("animecore-watched", all);
  renderEpisodeGrid();
}
function isWatched(animeId, seasonIndex, episodeIndex){
  const all = safeLocalGet("animecore-watched") || {};
  const key = `${animeId}:${seasonIndex}`;
  return Boolean(all[key] && all[key].includes(episodeIndex));
}

function renderSeasonTabs(){
  const tabsEl = document.getElementById("seasonTabs");
  if(!tabsEl) return;
  if(playerState.anime.seasons.length <= 1){ tabsEl.style.display = "none"; return; }
  tabsEl.innerHTML = playerState.anime.seasons.map((s, i) => `<button class="season-tab ${i === playerState.seasonIndex ? 'active' : ''}" data-season="${i}">${s.name}</button>`).join("");
}

function renderEpisodeGrid(){
  const gridEl = document.getElementById("episodeGrid");
  if(!gridEl) return;
  const season = playerState.anime.seasons[playerState.seasonIndex];
  const animeId = playerState.anime.id;
  const sIndex = playerState.seasonIndex;

  gridEl.innerHTML = season.episodes.map((ep, i) => {
    const isPlaying = i === playerState.episodeIndex;
    const hasSrc = Boolean(ep.src && ep.src.trim());
    const watched = isWatched(animeId, sIndex, i);
    return `
      <button class="episode-btn ${isPlaying ? 'playing' : ''} ${hasSrc ? 'has-src' : ''}" data-episode="${i}">
        <span class="ep-flag" title="${hasSrc ? "Video qo'shilgan" : "Video hali yo'q"}"></span>
        <span class="ep-num-badge">${String(ep.num).padStart(2, '0')}</span>
        <span class="ep-title-sm">${ep.title}</span>
        ${watched ? '<span class="ep-watched">&#10003;</span>' : ''}
      </button>`;
  }).join("");
}

