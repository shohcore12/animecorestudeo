function initScrollReveal(){
  if(!("IntersectionObserver" in window)){
    document.querySelectorAll(".scroll-reveal, .panel-card").forEach(el => el.classList.add("in-view"));
    return;
  }
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if(entry.isIntersecting){ entry.target.classList.add("in-view"); observer.unobserve(entry.target); }
    });
  }, { threshold: 0.12, rootMargin: "0px 0px -40px 0px" });
  document.querySelectorAll(".scroll-reveal, .panel-card").forEach(el => observer.observe(el));
}

const homeState = { search: "", genre: "all", sort: "default" };
