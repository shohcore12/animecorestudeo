function safeLocalGet(key){
  try{ const v = localStorage.getItem(key); return v ? JSON.parse(v) : null; }
  catch(e){ return null; }
}
function safeLocalSet(key, value){
  try{ localStorage.setItem(key, JSON.stringify(value)); } catch(e){ /* ignore */ }
}

function applyTheme(theme){
  document.documentElement.setAttribute("data-theme", theme);
  const btn = document.getElementById("themeToggle");
  if(btn) btn.textContent = theme === "light" ? "\u263E" : "\u2600";
  safeLocalSet("animecore-theme", theme);
}

function initTheme(){
  const saved = safeLocalGet("animecore-theme");
  applyTheme(saved === "light" ? "light" : "dark");
  const btn = document.getElementById("themeToggle");
  if(btn){
    btn.addEventListener("click", () => {
      const current = document.documentElement.getAttribute("data-theme");
      applyTheme(current === "light" ? "dark" : "light");
    });
  }
}

function revealHeroContent(){
  document.querySelectorAll(".reveal-up").forEach(el => requestAnimationFrame(() => el.classList.add("in")));
}

function hideIntro(overlay){
  if(!overlay){ revealHeroContent(); return; }
  overlay.classList.add("hide");
  revealHeroContent();
  setTimeout(() => overlay.remove(), 950);
}

function initIntro(){
  const overlay = document.getElementById("introOverlay");
  if(!overlay){ revealHeroContent(); return; }

  const alreadySeen = SITE_CONFIG.introOncePerSession && sessionStorage.getItem("animecore-intro-seen");
  const hasVideo = Boolean(SITE_CONFIG.introVideo && SITE_CONFIG.introVideo.trim());

  if(alreadySeen || !hasVideo){ hideIntro(overlay); return; }

  sessionStorage.setItem("animecore-intro-seen", "1");

  const video = document.getElementById("introVideo");
  const soundHint = document.getElementById("introSoundHint");
  video.src = SITE_CONFIG.introVideo;

  video.muted = false;
  video.play().catch(() => {
    video.muted = true;
    video.play().catch(() => {});
    if(soundHint) soundHint.classList.add("show");
    const unmuteOnce = () => {
      video.muted = false;
      if(soundHint) soundHint.classList.remove("show");
      overlay.removeEventListener("click", unmuteOnce);
    };
    overlay.addEventListener("click", unmuteOnce);
  });

  let done = false;
  const finish = () => { if(done) return; done = true; hideIntro(overlay); };

  video.addEventListener("ended", finish);
  video.addEventListener("error", finish);
  setTimeout(finish, SITE_CONFIG.introMaxSeconds * 1000);

  const skipBtn = document.getElementById("introSkip");
  if(skipBtn) skipBtn.addEventListener("click", (e) => { e.stopPropagation(); finish(); });
}
const musicState = { index: 0, playing: false };

function currentTrack(){ return SITE_CONFIG.musicTracks[musicState.index] || null; }

function updateMusicUI(){
  const launcher = document.getElementById("musicLauncher");
  const titleEl = document.getElementById("musicTrackTitle");
  const playBtn = document.getElementById("musicPlayBtn");
  const track = currentTrack();

  if(titleEl) titleEl.textContent = track ? track.title : "Hali trek qo'shilmagan";
  if(playBtn) playBtn.textContent = musicState.playing ? "\u23F8" : "\u25B6";
  if(launcher) launcher.classList.toggle("paused", !musicState.playing);
}

function playTrack(index){
  const audio = document.getElementById("bgMusic");
  if(!audio || !SITE_CONFIG.musicTracks.length) return;
  musicState.index = (index + SITE_CONFIG.musicTracks.length) % SITE_CONFIG.musicTracks.length;
  const track = currentTrack();
  audio.src = track.src;
  audio.play().then(() => { musicState.playing = true; updateMusicUI(); }).catch(() => { musicState.playing = false; updateMusicUI(); });
}

function toggleMusicPlay(){
  const audio = document.getElementById("bgMusic");
  if(!audio) return;
  if(!SITE_CONFIG.musicTracks.length) return;
  if(!audio.src){ playTrack(0); return; }
  if(audio.paused){ audio.play().then(() => { musicState.playing = true; updateMusicUI(); }); }
  else{ audio.pause(); musicState.playing = false; updateMusicUI(); }
}

function initMusicWidget(){
  const audio = document.getElementById("bgMusic");
  const launcher = document.getElementById("musicLauncher");
  const panel = document.getElementById("musicPanel");
  if(!audio || !launcher || !panel) return;

  updateMusicUI();

  launcher.addEventListener("click", () => { panel.classList.toggle("open"); });
  document.getElementById("musicPlayBtn").addEventListener("click", toggleMusicPlay);
  document.getElementById("musicNextBtn").addEventListener("click", () => playTrack(musicState.index + 1));
  document.getElementById("musicPrevBtn").addEventListener("click", () => playTrack(musicState.index - 1));

  const volume = document.getElementById("musicVolume");
  if(volume){
    volume.addEventListener("input", (e) => { audio.volume = Number(e.target.value); });
    audio.volume = Number(volume.value);
  }

  audio.addEventListener("ended", () => playTrack(musicState.index + 1));

  document.addEventListener("click", (e) => {
    if(!e.target.closest(".music-widget")) panel.classList.remove("open");
  });

  if(SITE_CONFIG.musicTracks.length){
    const tryAutostart = () => {
      if(!musicState.playing && !audio.src){ playTrack(0); }
      document.removeEventListener("click", tryAutostart);
      document.removeEventListener("keydown", tryAutostart);
      document.removeEventListener("touchstart", tryAutostart);
    };
    document.addEventListener("click", tryAutostart);
    document.addEventListener("keydown", tryAutostart);
    document.addEventListener("touchstart", tryAutostart);
  }
}

