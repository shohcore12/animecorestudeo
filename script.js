function aiSuggest(list){
  if(!list.length){ aiAddBubble("Hmm, bunga mos hech narsa topolmadim. Boshqa narsa sinab ko'raylik!"); aiShowMainMenu(); return; }
  const picks = list.slice(0, 3);
  aiAddBubble("Mana tavsiyalarim:");
  const body = document.getElementById("aiPanelBody");
  picks.forEach(a => {
    const link = document.createElement("a");
    link.href = `anime.html?id=${a.id}`;
    link.className = "ai-bubble";
    link.style.display = "block";
    link.innerHTML = `<b>${a.title}</b><span class="ai-suggestion">${a.genreLabel} \u00b7 \u2605 ${a.rating}</span>`;
    body.appendChild(link);
  });
  body.scrollTop = body.scrollHeight;
  aiShowMainMenu();
}

function aiHandleChoice(action){
  if(action === "random"){
    aiAddBubble("Tasodifiy anime tanla", true);
    setTimeout(() => {
      const pick = ANIME_DATA[Math.floor(Math.random() * ANIME_DATA.length)];
      aiAddBubble("Taqdir hukmini chiqardi! Bu ko'rishing kerak:");
      aiSuggest([pick]);
    }, 400);
    return;
  }
  if(action === "top"){
    aiAddBubble("Eng yuqori reytingli", true);
    setTimeout(() => {
      const sorted = ANIME_DATA.slice().sort((a,b) => parseFloat(b.rating) - parseFloat(a.rating));
      aiSuggest(sorted);
    }, 400);
    return;
  }
  if(action === "joke"){
    aiAddBubble("Bitta hazil ayt", true);
    setTimeout(() => {
      const jokes = [
        "Nega anime personaji hech qachon internet tezligidan shikoyat qilmaydi? Chunki u allaqachon 100 qismni bir zumda ko'rib chiqadi!",
        "Men sun'iy intellektman, lekin sening tanlovlaring meni ham hayratda qoldiradi ba'zida.",
        "Bilasanmi, men uxlamayman. Shuning uchun tunda ham bu yerdaman. Qo'rqinchlimi? Balki."
      ];
      aiAddBubble(jokes[Math.floor(Math.random() * jokes.length)]);
      aiShowMainMenu();
    }, 400);
    return;
  }
  if(action === "genre"){
    aiAddBubble("Janr bo'yicha tavsiya", true);
    setTimeout(() => {
      aiAddBubble("Qaysi kayfiyatdasan? Janrni tanla:");
      aiRenderChoices(GENRES.filter(g => g.key !== "all").map(g => ({ label: g.label, action: "genre-pick", genre: g.key })));
    }, 400);
    return;
  }
}

function wireAiChoices(){
  const el = document.getElementById("aiChoices");
  if(!el) return;
  el.addEventListener("click", (e) => {
    const btn = e.target.closest(".ai-choice-btn");
    if(!btn) return;
    const choice = el._choices[Number(btn.dataset.choice)];
    if(!choice) return;
    if(choice.action === "genre-pick"){
      aiAddBubble(choice.label, true);
      setTimeout(() => {
        const list = ANIME_DATA.filter(a => a.genres.includes(choice.genre));
        aiSuggest(list);
      }, 350);
    } else {
      aiHandleChoice(choice.action);
    }
  });
}

